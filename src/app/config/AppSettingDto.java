package app.config;

public class AppSettingDto {
	
	private String title;
	private String difyUrl;
	private int width;
	private int height;
	public String getTitle() {
		return title;
	}
	public void setTitle(String title) {
		this.title = title;
	}
	public String getDifyUrl() {
		return difyUrl;
	}
	public void setDifyUrl(String difyUrl) {
		this.difyUrl = difyUrl;
	}
	public int getWidth() {
		return width;
	}
	public void setWidth(int width) {
		this.width = width;
	}
	public int getHeight() {
		return height;
	}
	public void setHeight(int height) {
		this.height = height;
	}
	

}
